import React from 'react';
import { CheckCircle2, Circle, Clock, Info, AlertCircle } from 'lucide-react';

export default function TodayScheduleWidget({ tasks = [], onToggleTask }) {
  return (
    <div className="bg-white rounded-2xl border border-slate-200/80 shadow-xs p-5">
      <div className="flex items-center justify-between mb-4">
        <div>
          <h3 className="text-base font-bold text-slate-900">Today's Adaptive Schedule</h3>
          <p className="text-xs text-slate-500">Personalized sequence generated by the Performance Element</p>
        </div>
        <span className="text-xs font-semibold px-2.5 py-1 bg-indigo-50 text-indigo-700 rounded-full border border-indigo-100">
          {tasks.filter((t) => t.status === 'completed').length} of {tasks.length} Done
        </span>
      </div>

      <div className="space-y-3">
        {tasks.map((task) => {
          const isDone = task.status === 'completed';
          const isInProgress = task.status === 'in_progress';

          return (
            <div
              key={task.id}
              className={`p-3.5 rounded-xl border transition-all ${
                isDone
                  ? 'bg-slate-50/70 border-slate-200/60 opacity-80'
                  : isInProgress
                  ? 'bg-indigo-50/40 border-indigo-200'
                  : 'bg-white border-slate-200/80 hover:border-slate-300'
              }`}
            >
              <div className="flex items-start justify-between gap-3">
                {/* Left check & info */}
                <div className="flex items-start gap-3">
                  <button
                    onClick={() => onToggleTask(task.id, isDone ? 'pending' : 'completed')}
                    className="mt-0.5 text-slate-400 hover:text-indigo-600 transition-colors focus:outline-none"
                    aria-label={isDone ? 'Mark as incomplete' : 'Mark as complete'}
                  >
                    {isDone ? (
                      <CheckCircle2 className="w-5 h-5 text-emerald-500 fill-emerald-50" />
                    ) : (
                      <Circle className="w-5 h-5" />
                    )}
                  </button>

                  <div>
                    <div className="flex items-center gap-2 flex-wrap">
                      <span className={`text-sm font-semibold ${isDone ? 'line-through text-slate-500' : 'text-slate-900'}`}>
                        {task.topic}
                      </span>
                      <span className="text-[11px] font-medium text-slate-500 bg-slate-100 px-2 py-0.5 rounded-md">
                        {task.subject}
                      </span>
                      {isInProgress && (
                        <span className="text-[10px] font-bold text-indigo-600 bg-indigo-50 px-1.5 py-0.5 rounded-full border border-indigo-100 uppercase">
                          Current Focus
                        </span>
                      )}
                    </div>

                    <div className="flex items-center gap-4 mt-1.5 text-xs text-slate-500">
                      <span className="flex items-center gap-1 font-medium">
                        <Clock className="w-3.5 h-3.5 text-slate-400" />
                        {task.timeSlot} ({task.durationMinutes}m)
                      </span>
                      <span className="flex items-center gap-1">
                        <span className="text-slate-400">Retention:</span>
                        <strong className={task.retentionScore < 65 ? 'text-rose-600' : 'text-emerald-600'}>
                          {task.retentionScore}%
                        </strong>
                      </span>
                    </div>

                    {/* AI Justification Badge */}
                    <div className="mt-2 flex items-center gap-1.5 text-[11px] text-slate-500 bg-white/80 px-2 py-1 rounded-md border border-slate-100">
                      <Info className="w-3 h-3 text-indigo-500 shrink-0" />
                      <span>{task.aiReason}</span>
                    </div>
                  </div>
                </div>

                {/* Priority Indicator */}
                <span
                  className={`text-[10px] font-bold uppercase tracking-wider px-2 py-0.5 rounded-full shrink-0 ${
                    task.priority === 'high'
                      ? 'bg-rose-50 text-rose-600 border border-rose-100'
                      : 'bg-slate-100 text-slate-600'
                  }`}
                >
                  {task.priority}
                </span>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
}
